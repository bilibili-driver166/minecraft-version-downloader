@dataclass
class BaseInstallResult:
    version_id: str
    version_dir: Path
    files: int = 0
    assets: int = 0
    elapsed: float = 0.0


class BaseInstaller:
    def __init__(
        self,
        root: Path,
        callbacks: Callbacks,
        stop,
        workers: int = 4,
    ):
        self.root = Path(root).expanduser().resolve()
        self.callbacks = callbacks
        self.stop = stop
        self.workers = workers
        self.root.mkdir(parents=True, exist_ok=True)

    @property
    def versions_dir(self) -> Path:
        return self.root / "versions"

    @property
    def libraries_dir(self) -> Path:
        return self.root / "libraries"

    @property
    def assets_dir(self) -> Path:
        return self.root / "assets"

    def _version_dir(self, version_id: str) -> Path:
        return self.versions_dir / safe_segment(version_id)

    def install(
        self,
        version: VersionInfo,
        detail: Optional[dict] = None,
        *,
        include_assets: bool = True,
    ) -> BaseInstallResult:
        start = time.monotonic()
        version_dir = self._version_dir(version.id)
        version_dir.mkdir(parents=True, exist_ok=True)
        self.callbacks.log(f"开始安装 Minecraft {version.id}", "header")

        if detail is None:
            detail = self._fetch_detail(version, version_dir)
        else:
            self._save_version_json(version_dir, detail, version.id)

        self.callbacks.log(
            f"版本类型：{version.type_label}，发布时间：{version.datetime_label}",
            "dim",
        )
        asset_index = self._prepare_asset_index(detail)
        specs, natives = self._build_specs(
            version, detail, asset_index, include_assets=include_assets
        )
        total_bytes = sum(spec.size or 0 for spec in specs)
        self.callbacks.log(
            f"共 {len(specs)} 个文件，约 {format_bytes(total_bytes)}"
            + ("（含资源文件）" if include_assets else "（未包含资源文件）"),
            "info",
        )

        manager = DownloadManager(self.callbacks, self.stop, self.workers)
        summary = manager.run(specs, "下载游戏文件")
        self._check_cancel()

        if natives:
            self._extract_natives(version_dir, natives)

        if asset_index:
            self._materialize_legacy_assets(asset_index)

        asset_count = len((asset_index or {}).get("objects") or {})
        elapsed = time.monotonic() - start
        marker = {
            "version": version.id,
            "installed_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "asset_index": (asset_index or {}).get("id"),
            "asset_objects": asset_count,
            "files": summary.get("files", len(specs)),
        }
        atomic_write_json(version_dir / ".installed.json", marker)
        self.callbacks.progress(
            {
                "phase": f"{version.id} 原版文件已就绪",
                "percent": 100,
                "done_bytes": total_bytes,
                "total_bytes": total_bytes,
                "done_files": len(specs),
                "total_files": len(specs),
                "indeterminate": False,
            }
        )
        self.callbacks.log(
            f"原版 {version.id} 安装完成，用时 {elapsed:.1f} 秒", "success"
        )
        return BaseInstallResult(
            version_id=version.id,
            version_dir=version_dir,
            files=summary.get("files", len(specs)),
            assets=asset_count,
            elapsed=elapsed,
        )

    # -- 版本 JSON ---------------------------------------------------------

    def _fetch_detail(self, version: VersionInfo, version_dir: Path) -> dict:
        try:
            detail = fetch_version_detail(version, self.stop, self.callbacks)
        except InstallCancelled:
            raise
        except InstallError as exc:
            cached = version_dir / f"{version.id}.json"
            if cached.is_file():
                try:
                    detail = json.loads(cached.read_text(encoding="utf-8"))
                    self.callbacks.log(
                        f"在线读取版本 JSON 失败，使用已有本地文件：{exc}", "warn"
                    )
                    return detail
                except (OSError, json.JSONDecodeError):
                    pass
            raise
        self._save_version_json(version_dir, detail, version.id)
        return detail

    def _save_version_json(
        self, version_dir: Path, detail: dict, version_id: Optional[str] = None
    ) -> None:
        if version_id is None:
            version_id = str(detail.get("id") or version_dir.name)
        path = version_dir / f"{safe_segment(version_id)}.json"
        atomic_write_json(path, detail)

    # -- 资源索引 ----------------------------------------------------------

    def _prepare_asset_index(self, detail: dict) -> Optional[dict]:
        info = detail.get("assetIndex") or {}
        if not info.get("url"):
            return None
        asset_id = str(info.get("id") or "legacy")
        dest = self.assets_dir / "indexes" / f"{safe_segment(asset_id)}.json"
        expected_sha1 = str(info.get("sha1") or "").lower()

        if dest.is_file():
            if not expected_sha1:
                try:
                    return json.loads(dest.read_text(encoding="utf-8"))
                except (OSError, json.JSONDecodeError):
                    pass
            else:
                try:
                    if sha1_file(dest, stop=self.stop) == expected_sha1:
                        return json.loads(dest.read_text(encoding="utf-8"))
                except InstallCancelled:
                    raise
                except (OSError, json.JSONDecodeError):
                    pass

        self.callbacks.log(f"下载资源索引 {asset_id}…", "info")
        data = http_get(str(info["url"]), stop=self.stop, timeout=60, retries=3)
        if expected_sha1:
            import hashlib

            actual = hashlib.sha1(data).hexdigest()
            if actual != expected_sha1:
                raise InstallError(
                    f"资源索引校验失败：期望 {expected_sha1}，实际 {actual}"
                )
        try:
            index = json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise InstallError("资源索引不是有效 JSON") from exc
        dest.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_bytes(dest, data)
        count = len(index.get("objects") or {})
        self.callbacks.log(f"资源索引包含 {count} 个对象", "dim")
        return index

    # -- 下载规划 ----------------------------------------------------------

    def _build_specs(
        self,
        version: VersionInfo,
        detail: dict,
        asset_index: Optional[dict],
        *,
        include_assets: bool,
    ) -> tuple[list[DownloadSpec], list[NativeArchive]]:
        version_dir = self._version_dir(version.id)
        downloads = detail.get("downloads") or {}
        client = downloads.get("client")
        if not isinstance(client, dict) or not client.get("url"):
            raise InstallError(f"{version.id} 没有客户端下载信息")

        specs: list[DownloadSpec] = [
            DownloadSpec(
                url=str(client["url"]),
                dest=version_dir / f"{version.id}.jar",
                sha1=str(client.get("sha1") or "") or None,
                size=client.get("size"),
                label="客户端 client.jar",
            )
        ]

        library_specs, natives = collect_library_specs(
            detail.get("libraries") or [], self.libraries_dir
        )
        specs.extend(library_specs)

        logging_info = ((detail.get("logging") or {}).get("client") or {}).get("file")
        if isinstance(logging_info, dict) and logging_info.get("url"):
            file_id = str(logging_info.get("id") or "client-log.xml")
            try:
                file_name = safe_segment(file_id)
            except InstallError:
                file_name = "client-log.xml"
            specs.append(
                DownloadSpec(
                    url=str(logging_info["url"]),
                    dest=self.assets_dir / "log_configs" / file_name,
                    sha1=str(logging_info.get("sha1") or "") or None,
                    size=logging_info.get("size"),
                    label="日志配置",
                )
            )

        if include_assets and asset_index:
            objects = asset_index.get("objects") or {}
            for name, obj in objects.items():
                if not isinstance(obj, dict):
                    continue
                digest = str(obj.get("hash") or "")
                if not digest:
                    continue
                url = ASSET_OBJECT_BASE + digest[:2] + "/" + digest
                specs.append(
                    DownloadSpec(
                        url=url,
                        dest=self.assets_dir / "objects" / digest[:2] / digest,
                        sha1=digest,
                        size=obj.get("size"),
                        label=str(name),
                    )
                )
        return specs, natives

    # -- natives -----------------------------------------------------------

    def _extract_natives(
        self, version_dir: Path, natives: list[NativeArchive]
    ) -> None:
        natives_dir = version_dir / "natives"
        if natives_dir.exists():
            self.callbacks.log("清理旧的原生库文件…", "dim")
            shutil.rmtree(natives_dir)
        natives_dir.mkdir(parents=True, exist_ok=True)
        total_files = 0
        for archive in natives:
            self._check_cancel()
            if not archive.path.is_file():
                continue
            try:
                with zipfile.ZipFile(archive.path) as zf:
                    for info in zf.infolist():
                        if info.is_dir():
                            continue
                        name = info.filename.replace("\\", "/")
                        if not name:
                            continue
                        if any(
                            name == prefix.rstrip("/")
                            or name.startswith(prefix)
                            for prefix in archive.excludes
                        ):
                            continue
                        try:
                            target = safe_join(natives_dir, name)
                        except InstallError:
                            self.callbacks.log(
                                f"跳过不安全的原生库路径：{name}", "warn"
                            )
                            continue
                        target.parent.mkdir(parents=True, exist_ok=True)
                        with zf.open(info, "r") as src, target.open("wb") as dst:
                            shutil.copyfileobj(src, dst, 1024 * 256)
                        total_files += 1
            except zipfile.BadZipFile as exc:
                raise InstallError(f"原生库压缩包损坏：{archive.path.name}") from exc
        if total_files:
            self.callbacks.log(f"已解压 {total_files} 个原生库文件", "success")

    # -- 旧版资源映射 ------------------------------------------------------

    def _materialize_legacy_assets(self, asset_index: dict) -> None:
        virtual = bool(asset_index.get("virtual"))
        map_resources = bool(asset_index.get("map_to_resources"))
        if not virtual and not map_resources:
            return
        asset_id = str(asset_index.get("id") or "legacy")
        if virtual:
            target_root = self.assets_dir / "virtual" / safe_segment(asset_id)
            label = "assets/virtual"
        else:
            target_root = self.root / "resources"
            label = "resources"

        objects = asset_index.get("objects") or {}
        total = len(objects)
        done = 0
        copied = 0
        for name, obj in objects.items():
            self._check_cancel()
            done += 1
            if not isinstance(obj, dict):
                continue
            digest = str(obj.get("hash") or "")
            if not digest:
                continue
            source = self.assets_dir / "objects" / digest[:2] / digest
            if not source.is_file():
                continue
            try:
                target = safe_join(target_root, str(name))
            except InstallError:
                continue
            if target.is_file() and target.stat().st_size == source.stat().st_size:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            try:
                if target.exists():
                    target.unlink()
                try:
                    os.link(source, target)
                except OSError:
                    shutil.copy2(source, target)
                copied += 1
            except OSError as exc:
                self.callbacks.log(
                    f"无法生成旧版资源 {name}：{exc}", "warn"
                )
            if done % 80 == 0 or done == total:
                self.callbacks.progress(
                    {
                        "phase": f"整理旧版资源（{label}）",
                        "percent": int(done * 100 / max(1, total)),
                        "done_bytes": 0,
                        "total_bytes": 0,
                        "done_files": done,
                        "total_files": total,
                        "indeterminate": False,
                    }
                )
        if copied:
            self.callbacks.log(
                f"已为旧版本生成 {copied} 个 {label} 资源", "success"
            )

    def _check_cancel(self) -> None:
        if self.stop.is_set():
            raise InstallCancelled()


