def _headers(extra: Optional[dict] = None) -> dict:
    headers = {
        "User-Agent": USER_AGENT,
        "Accept": "*/*",
        "Accept-Encoding": "identity",
        "Connection": "close",
    }
    if extra:
        headers.update(extra)
    return headers


def _sleep(stop, seconds: float) -> None:
    if hasattr(stop, "wait"):
        stop.wait(seconds)
    else:
        time.sleep(seconds)


def http_get(
    url: str,
    *,
    timeout: float = 45,
    retries: int = 3,
    stop=None,
    headers: Optional[dict] = None,
) -> bytes:
    """带重试的 GET，返回完整 bytes。"""
    last_error: Optional[BaseException] = None
    for attempt in range(max(1, retries)):
        if stop is not None and stop.is_set():
            raise InstallCancelled()
        try:
            req = urlrequest.Request(url, headers=_headers(headers))
            with urlrequest.urlopen(req, timeout=timeout) as resp:
                status = getattr(resp, "status", 200)
                if status not in (200, 203, 206):
                    raise HttpError(url, status)
                data = resp.read()
            return data
        except urlerror.HTTPError as exc:
            body = ""
            try:
                body = exc.read().decode("utf-8", "replace")[:240]
            except Exception:
                pass
            last_error = HttpError(url, exc.code, body.replace("\n", " ").strip())
            # 404/403 等客户端错误通常重试没有意义
            if 400 <= exc.code < 500 and exc.code not in (408, 425, 429):
                raise last_error from exc
        except HttpError:
            raise
        except Exception as exc:  # noqa: BLE001 - 网络异常类型很多
            last_error = exc
        if attempt + 1 < retries:
            _sleep(stop, min(0.7 * (2 ** attempt), 4.0))
    if isinstance(last_error, InstallError):
        raise last_error
    raise InstallError(f"网络请求失败：{url}（{last_error}）") from last_error


def http_get_text(url: str, **kwargs) -> str:
    data = http_get(url, **kwargs)
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return data.decode("gbk", "replace")


