def _library_dest(libraries_dir: Path, entry: dict, name: str) -> Path:
    relative = entry.get("path") or maven_relative_path(name)
    return safe_join(libraries_dir, relative)


def collect_library_specs(
    libraries: Iterable[dict],
    libraries_dir: Path,
    *,
    os_name: Optional[str] = None,
    os_arch: Optional[str] = None,
    os_version: Optional[str] = None,
    features: Optional[dict] = None,
) -> tuple[list[DownloadSpec], list[NativeArchive]]:
    os_name = os_name or current_os_name()
    os_arch = normalize_arch(os_arch)
    os_version = os_version or platform.release()
    features = features or {}

    specs: list[DownloadSpec] = []
    natives: list[NativeArchive] = []
    arch_tag = _native_arch_tag(os_arch)

    for lib in libraries:
        if not isinstance(lib, dict):
            continue
        if not rules_allow(lib.get("rules"), os_name, os_arch, os_version, features):
            continue

        name = str(lib.get("name") or "")
        downloads = lib.get("downloads") or {}
        artifact = downloads.get("artifact")
        native_map = lib.get("natives") or {}

        if isinstance(artifact, dict) and artifact.get("url"):
            try:
                dest = _library_dest(libraries_dir, artifact, name)
            except InstallError:
                continue
            specs.append(
                DownloadSpec(
                    url=str(artifact["url"]),
                    dest=dest,
                    sha1=str(artifact.get("sha1") or "") or None,
                    size=artifact.get("size"),
                    label=name,
                )
            )
        elif not downloads and name:
            # Fabric profile 的库通常只有 name + url + sha1，没有 downloads 对象。
            try:
                relative = maven_relative_path(name)
                base = str(lib.get("url") or DEFAULT_LIBRARY_BASE)
                url = base if base.lower().endswith(".jar") else maven_url(base, name)
                dest = safe_join(libraries_dir, relative)
            except InstallError:
                continue
            specs.append(
                DownloadSpec(
                    url=url,
                    dest=dest,
                    sha1=str(lib.get("sha1") or "") or None,
                    size=lib.get("size"),
                    label=name,
                )
            )

        classifier_template = native_map.get(os_name)
        if classifier_template:
            classifier = str(classifier_template).replace("${arch}", arch_tag)
            classifier_entry = (downloads.get("classifiers") or {}).get(classifier)
            if isinstance(classifier_entry, dict) and classifier_entry.get("url"):
                try:
                    dest = _library_dest(libraries_dir, classifier_entry, name)
                except InstallError:
                    continue
                specs.append(
                    DownloadSpec(
                        url=str(classifier_entry["url"]),
                        dest=dest,
                        sha1=str(classifier_entry.get("sha1") or "") or None,
                        size=classifier_entry.get("size"),
                        label=f"{name} ({classifier})",
                    )
                )
                excludes = ()
                extract = lib.get("extract") or {}
                if isinstance(extract.get("exclude"), list):
                    excludes = tuple(str(item) for item in extract["exclude"])
                natives.append(NativeArchive(dest, excludes, name))

    # 某些旧版本会在多个库条目里引用同一个 natives jar，去重避免重复解压。
    unique_natives: list[NativeArchive] = []
    seen_native_paths: set[str] = set()
    for archive in natives:
        key = os.path.normcase(os.path.abspath(str(archive.path)))
        if key in seen_native_paths:
            continue
        seen_native_paths.add(key)
        unique_natives.append(archive)
    return specs, unique_natives


