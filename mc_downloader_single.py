    def _schedule_loader_refresh(self, force: bool = False) -> None:
        if self.busy:
            return
        if self.loader_key == "vanilla":
            self.loader_combo.configure(values=[], state="disabled")
            self.loader_version_var.set("")
            self.loader_hint.configure(text="原版模式", fg=DIM)
            self.loader_refresh_btn.configure(state="disabled")
