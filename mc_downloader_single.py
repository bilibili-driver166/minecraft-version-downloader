@dataclass(frozen=True)
class DownloadSpec:
    url: str
    dest: Path
    sha1: Optional[str] = None
    size: Optional[int] = None
    label: str = ""


def download_file(
    spec: DownloadSpec,
    *,
    stop,
    on_bytes: Optional[Callable[[int], None]] = None,
    timeout: float = 60,
    retries: int = 3,
    log: Callable[[str, str], None] = noop_log,
) -> bool:
    """下载单个文件，返回是否复用了已有文件。

    先写 .part，校验 SHA-1 后再原子替换，避免中断留下半个正式文件。
    """
    dest = spec.dest
    dest.parent.mkdir(parents=True, exist_ok=True)

    if dest.is_file():
        if spec.sha1:
            try:
                if sha1_file(dest, stop=stop) == spec.sha1.lower():
                    if on_bytes:
                        on_bytes(spec.size or dest.stat().st_size)
                    return True
                if log:
                    log(f"校验失败，重新下载：{dest.name}", "warn")
            except InstallCancelled:
                raise
            except OSError:
                pass
        elif spec.size is None:
            # 安装器之类没有校验值的文件：存在即复用
            if on_bytes:
                on_bytes(dest.stat().st_size)
            return True
        elif dest.stat().st_size == spec.size:
            if on_bytes:
                on_bytes(spec.size)
            return True

    part = dest.with_name(dest.name + ".part")
    last_error: Optional[BaseException] = None
    for attempt in range(max(1, retries)):
        if stop.is_set():
            raise InstallCancelled()
        sent = 0
        try:
            req = urlrequest.Request(spec.url, headers=_headers())
            with urlrequest.urlopen(req, timeout=timeout) as resp:
                status = getattr(resp, "status", 200)
                if status not in (200, 203):
                    raise HttpError(spec.url, status)
                with part.open("wb") as fh:
                    while True:
                        if stop.is_set():
                            raise InstallCancelled()
                        chunk = resp.read(CHUNK_SIZE)
                        if not chunk:
                            break
                        fh.write(chunk)
                        sent += len(chunk)
                        if on_bytes:
                            on_bytes(len(chunk))
                    fh.flush()

            actual_size = part.stat().st_size
            if spec.size is not None and actual_size != spec.size:
                raise InstallError(
                    f"文件大小不符：期望 {spec.size} 字节，实际 {actual_size} 字节"
                )
            if spec.sha1:
                actual_hash = sha1_file(part, stop=stop)
                if actual_hash.lower() != spec.sha1.lower():
                    raise InstallError(
                        f"SHA-1 校验失败：期望 {spec.sha1}，实际 {actual_hash}"
                    )
            os.replace(part, dest)
            return False
        except InstallCancelled:
            try:
                part.unlink(missing_ok=True)
            except OSError:
                pass
            raise
        except Exception as exc:  # noqa: BLE001
            last_error = exc
            if on_bytes and sent:
                on_bytes(-sent)
            try:
                part.unlink(missing_ok=True)
            except OSError:
                pass
            if attempt + 1 < retries:
                log(
                    f"下载重试 {attempt + 1}/{retries - 1}：{dest.name}（{exc}）",
                    "warn",
                )
                _sleep(stop, min(0.8 * (2 ** attempt), 5.0))

    if isinstance(last_error, InstallCancelled):
        raise last_error
    if isinstance(last_error, InstallError):
        raise last_error
    raise InstallError(f"下载失败：{dest.name}（{last_error}）") from last_error


class ProgressTracker:
    def __init__(
        self,
        callback: Callable[[dict], None],
        phase: str,
        total_files: int,
        total_bytes: int,
    ):
        self.callback = callback
        self.phase = phase
        self.total_files = total_files
        self.total_bytes = total_bytes
        self.done_files = 0
        self.done_bytes = 0
        self._lock = threading.Lock()
        self._last_emit = 0.0

    def add_bytes(self, count: int) -> None:
        with self._lock:
            self.done_bytes = max(0, self.done_bytes + count)
            if self.total_bytes > 0:
                self.done_bytes = min(self.done_bytes, self.total_bytes)
        self._maybe_emit()

    def file_done(self) -> None:
        with self._lock:
            self.done_files += 1
        self._maybe_emit()

    def event(self, force: bool = False) -> dict:
        with self._lock:
            if self.total_bytes > 0:
                percent = int(self.done_bytes * 100 / self.total_bytes)
            elif self.total_files > 0:
                percent = int(self.done_files * 100 / self.total_files)
            else:
                percent = 100
            event = {
                "phase": self.phase,
                "percent": max(0, min(100, percent)),
                "done_bytes": self.done_bytes,
                "total_bytes": self.total_bytes,
                "done_files": self.done_files,
                "total_files": self.total_files,
                "indeterminate": False,
            }
        return event

    def _maybe_emit(self, force: bool = False) -> None:
        now = time.monotonic()
        if not force and now - self._last_emit < 0.12:
            return
        self._last_emit = now
        try:
            self.callback(self.event(force=force))
        except Exception:
            # UI 异常不应该影响下载线程
            pass

    def finish(self) -> None:
        self._maybe_emit(force=True)


class _CombinedStop:
    def __init__(self, parent, local: threading.Event):
        self.parent = parent
        self.local = local

    def is_set(self) -> bool:
        return self.parent.is_set() or self.local.is_set()

    def wait(self, seconds: float) -> bool:
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            if self.is_set():
                return True
            time.sleep(min(0.1, max(0.0, deadline - time.monotonic())))
        return self.is_set()


class DownloadManager:
    """小型守护线程下载池。

    使用守护线程而不是 ThreadPoolExecutor，保证用户直接关闭窗口时进程可以退出。
    """

    def __init__(
        self,
        callbacks: Callbacks,
        stop,
        workers: int = 4,
    ):
        self.callbacks = callbacks
        self.stop = stop
        self.workers = max(1, min(int(workers or 4), 12))

    def run(
        self,
        specs: Iterable[DownloadSpec],
        phase: str,
    ) -> dict:
        # 同一目标只下一次；如果同一目标出现不同来源，保留第一个。
        unique: dict[str, DownloadSpec] = {}
        for spec in specs:
            key = os.path.normcase(os.path.abspath(str(spec.dest)))
            if key not in unique:
                unique[key] = spec
        tasks = list(unique.values())
        total_files = len(tasks)
        total_bytes = sum(spec.size or 0 for spec in tasks)

        tracker = ProgressTracker(
            self.callbacks.progress, phase, total_files, total_bytes
        )
        tracker._maybe_emit(force=True)
        if not tasks:
            tracker.finish()
            return {"files": 0, "cached": 0}

        queue_: "queue.Queue[DownloadSpec]" = queue.Queue()
        for spec in tasks:
            queue_.put(spec)

        local_abort = threading.Event()
        combined = _CombinedStop(self.stop, local_abort)
        lock = threading.Lock()
        errors: list[BaseException] = []
        cached_count = 0
        downloaded_count = 0

        def worker() -> None:
            nonlocal cached_count, downloaded_count
            while True:
                try:
                    spec = queue_.get_nowait()
                except queue.Empty:
                    return
                try:
                    if combined.is_set():
                        continue
                    cached = download_file(
                        spec,
                        stop=combined,
                        on_bytes=tracker.add_bytes,
                        log=self.callbacks.log,
                    )
                    with lock:
                        if cached:
                            cached_count += 1
                        else:
                            downloaded_count += 1
                    tracker.file_done()
                except InstallCancelled:
                    # 取消或首个错误后跳过剩余任务
                    continue
                except BaseException as exc:  # noqa: BLE001
                    with lock:
                        errors.append(exc)
                        error_count = len(errors)
                    self.callbacks.log(
                        f"文件下载失败：{spec.dest.name}（{exc}）", "error"
                    )
                    # 单个文件失败时继续下载其它文件，最后统一报错；
                    # 连续大量失败通常意味着网络已经中断，及时止损。
                    if error_count >= 12:
                        local_abort.set()
                finally:
                    queue_.task_done()

        threads = [
            threading.Thread(
                target=worker, name=f"mcdl-download-{i}", daemon=True
            )
            for i in range(min(self.workers, total_files))
        ]
        for thread in threads:
            thread.start()
        queue_.join()
        for thread in threads:
            thread.join(timeout=2)

        if self.stop.is_set():
            raise InstallCancelled()
        if errors:
            first = errors[0]
            if isinstance(first, InstallError):
                raise first
            raise InstallError(f"{phase}失败：{first}") from first

        tracker.finish()
        self.callbacks.log(
            f"{phase}完成：{downloaded_count} 个下载，{cached_count} 个复用",
            "success",
        )
        return {
            "files": total_files,
            "cached": cached_count,
            "downloaded": downloaded_count,
        }


