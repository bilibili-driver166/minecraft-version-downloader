def _decode_output(data: bytes) -> str:
    for encoding in ("utf-8", "gbk", "cp1252"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", "replace")


def _parse_versions_xml(text: str) -> list[str]:
    versions = re.findall(r"<version>\s*([^<\s]+)\s*</version>", text)
    # 去重并保持自然排序
    return sorted(set(versions), key=natural_key, reverse=True)


def neoforge_prefix(game_id: str) -> str:
    """把 MC 版本映射为 NeoForge 的版本前缀。

    1.21.5 -> 21.5.
    1.21   -> 21.0.
    1.21.1 -> 21.1.
    26.1.1 -> 26.1.
    26.3   -> 26.3.
    """
    match = re.match(r"^(\d+)\.(\d+)(?:\.(\d+))?", game_id)
    if not match:
        return ""
    major, minor, patch = match.groups()
    if int(major) == 1:
        if patch is None:
            return f"{int(minor)}.0."
        return f"{int(minor)}.{int(patch)}."
    return f"{int(major)}.{int(minor)}."


class LoaderCatalog:
    """查询加载器版本，带本地缓存，断网时可回退。"""

    def __init__(self, cache_dir: Path, callbacks: Callbacks, stop):
        self.cache_dir = Path(cache_dir)
        self.callbacks = callbacks
        self.stop = stop
        self._fabric_cache: dict[str, list[LoaderOption]] = {}
        self._forge_versions: Optional[list[str]] = None
        self._neoforge_versions: Optional[list[str]] = None
        self._neoforge_legacy_versions: Optional[list[str]] = None

    # -- 网络缓存 ----------------------------------------------------------

    @staticmethod
    def _fresh(path: Path, max_age: float = 12 * 3600) -> bool:
        try:
            return path.is_file() and (time.time() - path.stat().st_mtime) < max_age
        except OSError:
            return False

    def _cached_text(
        self, url: str, cache_name: str, label: str, force: bool = False
    ) -> str:
        path = self.cache_dir / cache_name
        if not force and self._fresh(path):
            try:
                return path.read_text(encoding="utf-8")
            except OSError:
                pass
        try:
            text = http_get_text(url, stop=self.stop, timeout=45, retries=3)
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(path.name + ".tmp")
            tmp.write_text(text, encoding="utf-8")
            os.replace(tmp, path)
            return text
        except InstallCancelled:
            raise
        except Exception as exc:  # noqa: BLE001
            if path.is_file():
                try:
                    self.callbacks.log(
                        f"在线获取 {label} 失败，使用本地缓存：{exc}", "warn"
                    )
                    return path.read_text(encoding="utf-8")
                except OSError:
                    pass
            raise InstallError(f"无法获取 {label}：{exc}") from exc

    def _cached_json(
        self, url: str, cache_name: str, label: str, force: bool = False
    ):
        path = self.cache_dir / cache_name
        if not force and self._fresh(path):
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                pass
        try:
            raw = http_get(url, stop=self.stop, timeout=45, retries=3)
            data = json.loads(raw.decode("utf-8"))
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(path.name + ".tmp")
            tmp.write_bytes(raw)
            os.replace(tmp, path)
            return data
        except InstallCancelled:
            raise
        except Exception as exc:  # noqa: BLE001
            if path.is_file():
                try:
                    self.callbacks.log(
                        f"在线获取 {label} 失败，使用本地缓存：{exc}", "warn"
                    )
                    return json.loads(path.read_text(encoding="utf-8"))
                except (OSError, json.JSONDecodeError):
                    pass
            raise InstallError(f"无法获取 {label}：{exc}") from exc

    # -- 查询 --------------------------------------------------------------

    def fabric_versions(self, game_id: str, force: bool = False) -> list[LoaderOption]:
        if game_id in self._fabric_cache and not force:
            return self._fabric_cache[game_id]
        url = f"{FABRIC_META}/versions/loader/{quote(game_id, safe='')}"
        cache_name = f"fabric-loader-{re.sub(r'[^A-Za-z0-9_.-]+', '_', game_id)}.json"
        try:
            data = self._cached_json(
                url, cache_name, f"Fabric 加载器（{game_id}）", force=force
            )
        except InstallError as exc:
            message = str(exc)
            if "HTTP 400" in message or "HTTP 404" in message:
                raise InstallError(f"Fabric 暂不支持 Minecraft {game_id}") from exc
            raise
        if not isinstance(data, list):
            raise InstallError("Fabric 返回了异常数据")

        all_options: list[LoaderOption] = []
        for entry in data:
            if not isinstance(entry, dict):
                continue
            loader = entry.get("loader") or {}
            version = str(loader.get("version") or "")
            if not version:
                continue
            all_options.append(
                LoaderOption(version=version, stable=bool(loader.get("stable", False)))
            )
        # Fabric API 只把「当前稳定版」标为 stable=true，旧版本也会是 false。
        # 这里把不高于当前稳定版的旧版本都视为可选稳定版，只有比稳定版更新的
        # 预发布版才标成测试版。
        stable_versions = [item.version for item in all_options if item.stable]
        newest_stable = (
            max(stable_versions, key=natural_key) if stable_versions else None
        )
        normalized: list[LoaderOption] = []
        for item in all_options:
            is_stable = item.stable
            if newest_stable and natural_key(item.version) <= natural_key(newest_stable):
                is_stable = True
            normalized.append(LoaderOption(item.version, is_stable))
        normalized.sort(
            key=lambda item: (item.stable, natural_key(item.version)), reverse=True
        )
        self._fabric_cache[game_id] = normalized
        return normalized

    def _get_forge_all(self, force: bool = False) -> list[str]:
        if self._forge_versions is None or force:
            text = self._cached_text(
                FORGE_METADATA_URL, "forge-maven.xml", "Forge 版本列表", force=force
            )
            self._forge_versions = _parse_versions_xml(text)
        return self._forge_versions

    def forge_versions(self, game_id: str, force: bool = False) -> list[LoaderOption]:
        prefix = f"{game_id}-"
        versions = [v for v in self._get_forge_all(force=force) if v.startswith(prefix)]
        return [LoaderOption(version=v, stable=True) for v in versions]

