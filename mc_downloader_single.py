def probe_java(path: str | Path, timeout: float = 8.0) -> Optional[JavaInfo]:
    executable = _java_executable(Path(path))
    if not executable:
        return None
    try:
        process = subprocess.run(
            [str(executable), "-version"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=timeout,
            creationflags=CREATE_NO_WINDOW,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    text = _decode(process.stdout or b"")
    match = re.search(r'version\s+"([^"]+)"', text)
    if not match:
        match = re.search(r"version\s+([^\s]+)", text)
    if not match:
        return None
    version = match.group(1)
    major_match = re.match(r"(?:1\.)?(\d+)", version)
    if not major_match:
        return None
    return JavaInfo(str(executable), version, int(major_match.group(1)))


def _candidate_paths(root: Optional[Path] = None) -> list[Path]:
    result: list[Path] = []

    def add(path) -> None:
        if path:
            result.append(Path(path))

    java_home = os.environ.get("JAVA_HOME")
    if java_home:
        add(Path(java_home) / "bin" / ("java.exe" if os.name == "nt" else "java"))

    which = shutil.which("java")
    if which:
        add(which)

    if root:
        try:
            for pattern in (
                "runtime/*/*/*/bin/java.exe",
                "runtime/*/*/bin/java.exe",
                "runtime/*/bin/java.exe",
            ):
                result.extend(root.glob(pattern))
        except OSError:
            pass

    patterns: list[tuple[Path, str]] = []
    if os.name == "nt":
        bases = []
        for env_name in ("ProgramFiles", "ProgramFiles(x86)", "ProgramData"):
            value = os.environ.get(env_name)
            if value:
                bases.append(Path(value))
        local = os.environ.get("LOCALAPPDATA")
        if local:
            bases.append(Path(local) / "Programs")
        vendors = (
            "Java",
            "Eclipse Adoptium",
            "Eclipse Foundation",
            "Microsoft",
            "Amazon Corretto",
            "Zulu",
            "BellSoft",
            "Semeru",
            "OpenJDK",
            "RedHat",
        )
        for base in bases:
            for vendor in vendors:
                patterns.append((base / vendor, "*/bin/java.exe"))
        for base in bases:
            patterns.append((base / "Common Files" / "Oracle" / "Java", "javapath/java.exe"))
    elif platform.system() == "Darwin":
        patterns.append(
            (Path("/Library/Java/JavaVirtualMachines"), "*/Contents/Home/bin/java")
        )
        patterns.append((Path("/System/Library/Java/JavaVirtualMachines"), "*/Contents/Home/bin/java"))
    else:
        patterns.append((Path("/usr/lib/jvm"), "*/bin/java"))
        patterns.append((Path("/usr/java"), "*/bin/java"))
        patterns.append((Path("/opt/java"), "*/bin/java"))

    for base, pattern in patterns:
        try:
            if base.is_dir():
                result.extend(base.glob(pattern))
        except OSError:
            pass
    return result


def detect_java_candidates(
    root: Optional[Path] = None,
    extra: Optional[Iterable[str]] = None,
) -> list[JavaInfo]:
    seen: set[str] = set()
    infos: list[JavaInfo] = []
    for candidate in [*(extra or []), *_candidate_paths(root)]:
        try:
            key = os.path.normcase(os.path.abspath(str(candidate)))
        except OSError:
            continue
        if key in seen:
            continue
        seen.add(key)
        info = probe_java(candidate)
        if info:
            real_key = os.path.normcase(os.path.abspath(info.path))
            if real_key in {os.path.normcase(os.path.abspath(i.path)) for i in infos}:
                continue
            infos.append(info)
    infos.sort(key=lambda item: (item.major, item.version), reverse=True)
    return infos


def pick_java(required_major: Optional[int], candidates: list[JavaInfo]) -> Optional[JavaInfo]:
    if not candidates:
        return None
    if required_major:
        exact = [item for item in candidates if item.major == required_major]
        if exact:
            return exact[0]
        newer = [item for item in candidates if item.major >= required_major]
        if newer:
            return min(newer, key=lambda item: item.major)
    return candidates[0]


def requirement_text(required_major: Optional[int]) -> str:
    if required_major:
        return f"该版本要求 Java {required_major}+"
    return "原版下载不需要 Java；Forge / NeoForge 安装需要"


