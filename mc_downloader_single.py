        if self._neoforge_versions is None or force:
            text = self._cached_text(
                NEOFORGE_METADATA_URL,
                "neoforge-maven.xml",
                "NeoForge 版本列表",
                force=force,
            )
            self._neoforge_versions = _parse_versions_xml(text)
